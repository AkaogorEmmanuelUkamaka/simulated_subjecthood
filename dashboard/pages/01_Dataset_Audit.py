import sys
from pathlib import Path

import streamlit as st

# Make project root importable
sys.path.append(str(Path(__file__).resolve().parents[2]))

from dashboard.utils import (
    section_header,
    display_figure,
    load_table,
)


# ==========================================================
# Page Configuration
# ==========================================================

st.set_page_config(
    page_title="Dataset Audit",
    page_icon="📋",
    layout="wide",
)

section_header("📋 Dataset Audit")


# ==========================================================
# Introduction
# ==========================================================

st.markdown(
    """
The **Dataset Audit** provides an overview of the
Heart Failure Prediction Dataset used throughout the
empirical validation pipeline.

This page summarises the dataset characteristics,
highlights missing data patterns, and presents the
visualisation generated during the analytical phase.

**No analysis is performed here.**
The dashboard only presents outputs generated by the
analytical pipeline.
"""
)


# ==========================================================
# Summary Statistics
# ==========================================================

section_header("📊 Summary Statistics")

col1, col2, col3, col4 = st.columns(4)

with col1:
    st.metric("Observations", "918")

with col2:
    st.metric("Variables", "12")

with col3:
    st.metric("Target Variable", "HeartDisease")

with col4:
    st.metric("Missing Values", "0")


# ==========================================================
# Dataset Audit Visualisation
# ==========================================================

section_header("📈 Dataset Audit Visualisation")

display_figure(
    "figure_1_missingness_heatmap.png",
    caption="Dataset Audit Visualisation: Missingness Heatmap",
)


# ==========================================================
# Interpretation
# ==========================================================

section_header("💡 Interpretation")

st.info(
    """
The dataset audit indicates that the Heart Failure Prediction
Dataset contains 918 observations and 12 variables, with no
missing values detected.

Consequently, no missing-value imputation was required for
the variables examined.

Although the absence of missing values simplifies data
preparation, it does not independently establish the dataset's
representativeness, measurement quality, or suitability for
every downstream analytical task. These considerations are
examined in subsequent sections of the dashboard.
"""
)


# ==========================================================
# Publication Table
# ==========================================================

section_header("📄 Publication Table")

st.markdown(
    """
The table below summarises the principal characteristics of the
Heart Failure Prediction Dataset used throughout the empirical
validation pipeline.
"""
)

dataset_summary = load_table(
    "table_1_dataset_characteristics.csv"
)

st.dataframe(
    dataset_summary,
    use_container_width=True,
)


# ==========================================================
# Downloads
# ==========================================================

section_header("📥 Downloads")

with st.container():

    csv = dataset_summary.to_csv(index=False).encode("utf-8")

    st.download_button(
        label="📥 Download Table 1 (CSV)",
        data=csv,
        file_name="table_1_dataset_characteristics.csv",
        mime="text/csv",
    )


# ==========================================================
# Key Takeaways
# ==========================================================

section_header("✅ Key Takeaways")

st.success(
    """
- The Heart Failure Prediction Dataset contains **918 observations** across **12 variables**.
- No missing values were detected in the dataset.
- No missing-value imputation was therefore required for the variables examined.
- Dataset completeness does not, by itself, establish representativeness or overall analytical suitability.
- The dataset audit visualisation and Table 1 present the supporting outputs for this module.
"""
)
