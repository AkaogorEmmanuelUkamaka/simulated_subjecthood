section_header("🎯 Why This Dataset?")

st.markdown(
    """
The Heart Failure Prediction Dataset was selected because it provides
an appropriate benchmark for evaluating governance risks associated
with simulated subjecthood.

Key characteristics include:

- A real-world healthcare prediction task with practical relevance.
- Demographic attributes (e.g., age and sex) suitable for subgroup
  and fairness analyses.
- A binary clinical outcome that supports classification modelling.
- Multiple clinical predictors representing heterogeneous patient
  characteristics.
- Sufficient diversity to evaluate representational integrity,
  synthetic bias amplification, calibration, and governance
  interventions.
- A manageable dataset size that enables reproducible local
  experimentation while remaining computationally efficient.
"""
)    


