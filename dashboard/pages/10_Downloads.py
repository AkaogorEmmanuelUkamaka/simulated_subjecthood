import sys
from pathlib import Path

import streamlit as st

# Make project root importable
sys.path.append(str(Path(__file__).resolve().parents[2]))

from dashboard.utils import (
    section_header,
)


# ==========================================================
# Project Directories
# ==========================================================

PROJECT_ROOT = Path(__file__).resolve().parents[2]

OUTPUTS_DIR = PROJECT_ROOT / "outputs"

TABLES_DIR = OUTPUTS_DIR / "tables"

FIGURES_DIR = OUTPUTS_DIR / "figures"

REPORTS_DIR = OUTPUTS_DIR / "reports"


# ==========================================================
# Page Configuration
# ==========================================================

st.set_page_config(
    page_title="Downloads",
    page_icon="📥",
    layout="wide",
)

section_header("📥 Research Artefacts & Downloads")


# ==========================================================
# Introduction
# ==========================================================

st.markdown(
    """
This repository provides access to the datasets, publication-ready
tables, figures, and supplementary materials generated during the
empirical evaluation of the proposed governance framework.

All downloadable assets were produced directly from the analytical
pipeline without manual modification, ensuring reproducibility and
consistency with the accompanying research paper.
"""
)


# ==========================================================
# Project Outputs Overview
# ==========================================================

section_header("📊 Project Outputs")

col1, col2, col3, col4 = st.columns(4)

table_files = sorted(
    [
        f
        for f in TABLES_DIR.glob("table_*.csv")
        if f.is_file()
    ],
    key=lambda x: (
        int(x.stem.split("_")[1]),
        x.stem,
    ),
)
figure_files = sorted(
    [
        f
        for f in FIGURES_DIR.glob("figure_*.png")
        if f.is_file()
    ]
)
report_files = (
    sorted(
        [
            f
            for f in REPORTS_DIR.iterdir()
            if f.is_file() and not f.name.startswith(".")
        ]
    )
    if REPORTS_DIR.exists()
    else []
)

with col1:
    st.metric(
        "Tables",
        len(table_files),
    )

with col2:
    st.metric(
        "Figures",
        len(figure_files),
    )

with col3:
    st.metric(
        "Notebook Modules",
        "9",
    )

with col4:
    st.metric(
        "Governance Experiments",
        "6",
    )


