# ==========================================================
# Scope and Limitations
# ==========================================================

section_header("🔎 Scope and Limitations")

st.markdown(
    """
The governance analysis distinguishes between:

- **Policy threshold adjustments:** Changes in decision rules
  that may affect allocation or classification outcomes.

- **Review capacity constraints:** Operational limits on the
  availability of human review.

- **Simulated outcomes:** Results produced under specified
  computational assumptions and scenario settings.

- **Institutional governance misfit:** A broader condition
  requiring evidence about actual institutional policies,
  responsibilities, practices, and operational requirements.

The simulations can inform the conceptual discussion of
governance misfit. Establishing actual institutional misfit
requires additional contextual and institutional evidence.

The results should not be interpreted as causal evidence
of institutional failure or as an empirical assessment
of a real organisation's governance arrangements.
"""
)


