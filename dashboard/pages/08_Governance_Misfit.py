# Interpretation
# ==========================================================

section_header("💡 Interpretation")

st.info(
    """
Model performance alone does not determine the outcomes of
AI-enabled decision processes. Institutional rules, decision
thresholds, and available review capacity may also influence
how computational outputs are translated into decisions.

Changing a decision threshold may alter the number of cases
selected for a particular action. Similarly, limited review
capacity may constrain the number of cases receiving
additional human scrutiny.

These scenarios illustrate why technical evaluation should
be considered alongside institutional and operational
conditions.

However, the simulations do not independently demonstrate
that a real institution has adopted unsuitable policies or
that its governance arrangements are misaligned with its
operational context.
"""
)


