"""
Utility functions for the Streamlit dashboard.

This module provides reusable helper functions for loading
tables, figures, and other project assets generated by the
empirical validation pipeline.

Project:
Operational Evaluation of Governance Risks in Simulated Subjecthood
"""

from pathlib import Path

import pandas as pd
import streamlit as st


# ==========================================================
# Project Directories
# ==========================================================

PROJECT_ROOT = Path(__file__).resolve().parent.parent

OUTPUTS_DIR = PROJECT_ROOT / "outputs"

TABLES_DIR = OUTPUTS_DIR / "tables"

FIGURES_DIR = OUTPUTS_DIR / "figures"

REPORTS_DIR = OUTPUTS_DIR / "reports"


# ==========================================================
# Load Table
# ==========================================================

@st.cache_data
def load_table(filename: str) -> pd.DataFrame:
    """
    Load a CSV table from the outputs directory.

    Args:
        filename:
            Name of the CSV file.

    Returns:
        DataFrame.
    """

    return pd.read_csv(TABLES_DIR / filename)


# ==========================================================
# Display Figure
# ==========================================================

def display_figure(
    filename: str,
    caption: str | None = None,
) -> None:
    """
    Display a saved figure.

    Args:
        filename:
            Figure filename.

        caption:
            Optional figure caption.
    """

    st.image(
        FIGURES_DIR / filename,
        caption=caption,
        use_container_width=True,
    )


# ==========================================================
# Section Header
# ==========================================================

def section_header(title: str) -> None:
    """
    Display a standard dashboard section header.

    Args:
        title:
            Section title.
    """

    st.markdown(f"## {title}")

    st.divider()


