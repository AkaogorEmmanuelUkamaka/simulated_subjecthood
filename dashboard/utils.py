
"""
Utility functions for the Streamlit dashboard.

This module provides reusable helper functions for loading
tables, displaying figures, and accessing project assets
generated by the empirical validation pipeline.

Project:
Simulated Subjecthood and the Governance of Computational
Representation: From Predictive Performance to Institutional Power.
"""

from pathlib import Path

import pandas as pd
import streamlit as st


# ==========================================================
# Project Directories
# ==========================================================

PROJECT_ROOT = Path(__file__).resolve().parent.parent

OUTPUTS_DIR = PROJECT_ROOT / "outputs"

TABLES_DIR = OUTPUTS_DIR / "tables"

FIGURES_DIR = OUTPUTS_DIR / "figures"

REPORTS_DIR = OUTPUTS_DIR / "reports"


# ==========================================================
# Load Table
# ==========================================================

@st.cache_data
def load_table(filename: str) -> pd.DataFrame:
    """
    Load a CSV table from the outputs directory.

    Args:
        filename:
            Name of the CSV file.

    Returns:
        Loaded pandas DataFrame.
    """

    file_path = TABLES_DIR / filename

    if not file_path.is_file():
        st.error(
            f"Table not found: {filename}. "
            "Please check the outputs/tables directory."
        )
        st.stop()

    try:
        return pd.read_csv(file_path)

    except (OSError, pd.errors.ParserError, UnicodeDecodeError) as error:
        st.error(
            f"Unable to load table: {filename}. "
            f"Details: {error}"
        )
        st.stop()


# ==========================================================
# Display Figure
# ==========================================================

def display_figure(
    filename: str,
    caption: str | None = None,
) -> None:
    """
    Display a saved figure from the outputs directory.

    Args:
        filename:
            Figure filename.

        caption:
            Optional figure caption.
    """

    file_path = FIGURES_DIR / filename

    if not file_path.is_file():
        st.error(
            f"Figure not found: {filename}. "
            "Please check the outputs/figures directory."
        )
        st.stop()

    try:
        st.image(
            str(file_path),
            caption=caption,
            use_container_width=True,
        )

    except OSError as error:
        st.error(
            f"Unable to display figure: {filename}. "
            f"Details: {error}"
        )
        st.stop()


# ==========================================================
# Section Header
# ==========================================================

def section_header(title: str) -> None:
    """
    Display a standard dashboard section header.

    Args:
        title:
            Section title.
    """

    st.markdown(f"## {title}")

    st.divider()
